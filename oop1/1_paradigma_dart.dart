/**
 * paradigma adalah pola pikir, kerangka, cara pandang
 * paradigma oop = didasari pada konsep objek yang memiliki
 * atribute serta dapat melakukan operasi atau prosedur tertentu
 *
 * 4 pilar oop
 * - encapsulation
 * - abstraction
 * - inheritance
 * - polymophism
 * 
 * => Encapsulation
 * => Ibarat sebuah kantong yang menyimpan sesuatu dalam pemograman
 * => Berfungsi
 * => Mengumpulkan data dan tidak dapat diakses langsung dari luar
 * => pada kasus "Ucup Guerero" kita tidak bisa mengubah
 * berat badan dari Ucup tapi kita bisa menambahkannya
 * melalui fungsi / method makan().
 * 
 * => Abstraction
 * => Bisa dibilang penerapan alami dari Encapsulation
 * => yang mana Abstraction berarti sebuah objek yang hanya
 * menunjukan operasinya secara high-level.
 * => Misalnya kita hanya cukup tau bagaimana Ucup Guerero makan.
 * => namun kita tidak perlu bagaimana sistem metabolisme biologis dalam
 * dalam tubuh si Ucup, yang membuat berat badannya bertambah
 * 
 * => Inheritance
 * => Beberapa objek bisa memiliki beberapa karakteristik atau
 * perilaku yang sama.,
 * => namun mereka bukanlah objek yang sama
 * => Inheritance pada Ucup Guerero memiliki sifat dan perilaku yang umum
 * dengan Manusia lain. seperti berat, warna, tinggi badan dsb.
 * Maka Ucup Guerero sebagai Objek Turunan (Subclass).
 * => induk classnya di sebut (Superclass)
 * 
 *  => Polymorphism
 * => "Banyak Bentuk"
 * => Objek daapat memiliki bentuk atau implementasi yang berbeda-beda
 * => pada satu metode yang sama
 * => Manusia bergerak, akan tetapi cara
 * gerak Ucup Guerero dengan cara gerak Kenzie Samurai berbeda
 * itulah yang merupakan contoh dari Polymorphsim. 
 *
 */